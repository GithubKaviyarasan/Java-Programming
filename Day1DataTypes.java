
class Day1DataTypes {

    public static void main(String[] args) {

        // // Java Data Types :
        // // -------------------
        // // 1. byte
        // // 2. short
        // // 3. int
        // // 4. long
        // // 5. float
        // // 6. double
        // // 7. char
        // // 8. boolean
        // // 9. String
        // // 1. String - Text
        String name = "Kaviyarasan";
        System.out.println("Name: " + name);

        // // 2. int - Whole Numbers
        int salary = 25000;
        System.out.println("Salary: " + salary);

        // // 3. float - Decimal Numbers
        float price = 799.99f;
        System.out.println("Price: " + price);

        // // 4. double - Double Precision Decimal Numbers
        double dSalary = 25000.00;
        System.out.println("Double Salary: " + dSalary);

        // // 5. char - Single Character
        char grade = 'A';
        System.out.println("Grade: " + grade);

        // // 6. boolean - True or False
        boolean status = true;
        System.out.println("Status: " + status);

        // // 7. byte - 8-bit signed integer
        byte age = 22;
        System.out.println("Age: " + age);

        // // 8. short - 16-bit signed integer
        short number = 1000;
        System.out.println("Number: " + number);

        // // 9. long - 64-bit signed integer
        long population = 100000L;
        System.out.println("Population: " + population);

    }
}
